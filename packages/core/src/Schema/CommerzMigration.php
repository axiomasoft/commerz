<?php

declare(strict_types=1);

namespace Commerz\Schema;

use Closure;
use Commerz\Attributes\Spi;
use Commerz\Attributes\SpiKind;
use Illuminate\Container\Container;
use Illuminate\Database\Connection;
use Illuminate\Database\DatabaseManager;
use Illuminate\Database\Migrations\Migration;
use Illuminate\Database\Schema\Blueprint;
use Illuminate\Database\Schema\Builder;
use Illuminate\Database\Schema\ColumnDefinition;
use Illuminate\Database\Schema\ForeignKeyDefinition;

/**
 * Base of every Commerz migration: runs on `commerz.connection`, names tables through `TableNames` and constraints
 * through `ConstraintNames` (PostgreSQL's `{table}_pkey` becomes `{table}_pk`). Released migrations never change;
 * a schema change is a new migration.
 *
 * ```php
 * return new class extends CommerzMigration {
 *     public function up(): void
 *     {
 *         $this->create('stock_levels', function (Blueprint $table): void {
 *             $this->uuidPrimary($table);
 *             $this->ref($table, 'sellable');
 *             $this->money($table, 'price');
 *             $this->timestampsTz($table);
 *         });
 *     }
 * };
 * ```
 */
#[Spi(kind: SpiKind::Implement, since: '0.1')]
abstract class CommerzMigration extends Migration
{
    public function getConnection(): ?string
    {
        return $this->tables()->connection();
    }

    /** Physical name of a logical table: `stock_levels` → `cmz_stock_levels`. */
    protected function table(string $logical): string
    {
        return $this->tables()->table($logical);
    }

    protected function tables(): TableNames
    {
        return Container::getInstance()->make(TableNames::class);
    }

    protected function schema(): Builder
    {
        return $this->db()->getSchemaBuilder();
    }

    protected function db(): Connection
    {
        return Container::getInstance()->make(DatabaseManager::class)->connection($this->getConnection());
    }

    /**
     * Creates the table and renames its primary key to `{table}_pk`.
     *
     * @param  Closure(Blueprint): void  $define
     * @return string the physical table name
     */
    protected function create(string $logical, Closure $define): string
    {
        $table = $this->table($logical);

        $this->schema()->create($table, $define);

        $primary = $this->db()->selectOne(
            "select conname from pg_constraint where conrelid = ?::regclass and contype = 'p'",
            [$table],
            useReadPdo: false,
        );
        $current = is_object($primary) && property_exists($primary, 'conname') && is_string($primary->conname) ? $primary->conname : null;
        $wanted = ConstraintNames::primary($table);

        if ($current !== null && $current !== $wanted) {
            $this->db()->statement("alter table \"{$table}\" rename constraint \"{$current}\" to \"{$wanted}\"");
        }

        return $table;
    }

    /** Drops the table if it exists; for `down()`. */
    protected function drop(string $logical): void
    {
        $this->schema()->dropIfExists($this->table($logical));
    }

    /** `uuid` primary key; the value is a UUIDv7 generated by the application before INSERT. */
    protected function uuidPrimary(Blueprint $table, string $column = 'id'): ColumnDefinition
    {
        return $table->uuid($column)->primary();
    }

    /** `bigint generated always as identity` primary key, for append-only journals. */
    protected function identityPrimary(Blueprint $table, string $column = 'id'): ColumnDefinition
    {
        return $table->bigInteger($column)->generatedAs()->always()->primary();
    }

    /**
     * `{name}_minor bigint` plus a shared `char(3)` currency column (added once per table).
     */
    protected function money(Blueprint $table, string $name, bool $nullable = false, string $currency = 'currency'): ColumnDefinition
    {
        $amount = $table->bigInteger("{$name}_minor")->nullable($nullable);

        $exists = false;

        foreach ($table->getColumns() as $column) {
            $exists = $exists || $column->get('name') === $currency;
        }

        if (! $exists) {
            $table->char($currency, 3)->nullable($nullable);
        }

        return $amount;
    }

    /** `{name}_ref varchar(191)` holding `type:id` of something another package or the host owns; no foreign key. */
    protected function ref(Blueprint $table, string $name, bool $nullable = false): ColumnDefinition
    {
        return $table->string("{$name}_ref", 191)->nullable($nullable);
    }

    /** `created_at` and `updated_at` as non-null `timestamptz(6)` defaulting to now(). */
    protected function timestampsTz(Blueprint $table): void
    {
        $table->timestampTz('created_at', 6)->useCurrent();
        $table->timestampTz('updated_at', 6)->useCurrent();
    }

    /** @param  string|list<string>  $columns */
    protected function index(Blueprint $table, string|array $columns): void
    {
        $table->index($columns, ConstraintNames::index($table->getTable(), $columns));
    }

    /** @param  string|list<string>  $columns */
    protected function unique(Blueprint $table, string|array $columns): void
    {
        $table->unique($columns, ConstraintNames::unique($table->getTable(), $columns));
    }

    /** @param  string|list<string>  $columns */
    protected function foreign(Blueprint $table, string|array $columns): ForeignKeyDefinition
    {
        return $table->foreign($columns, ConstraintNames::foreign($table->getTable(), $columns));
    }

    /** Adds `CHECK ($expression)` named `{table}_{name}_ck` to an existing table. */
    protected function check(string $table, string $name, string $expression): void
    {
        $constraint = ConstraintNames::check($table, $name);

        $this->db()->statement("alter table \"{$table}\" add constraint \"{$constraint}\" check ({$expression})");
    }
}
